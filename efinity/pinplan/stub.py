"""Stub compile for the phase 4 pin plan: a placeholder core around the Interface Designer ports.

    python3 efinity/pinplan/stub.py          (after pinplan.py; run.sh calls it)
    cd efinity/pinplan/build && efx_run ti60f225_pinplan.xml --prj --flow compile ... (run.sh does this)

Writes into efinity/pinplan/build:
- ti60f225_pinplan_stub.v: every core-side output port driven from a 32-bit LFSR on ram_clk, every input
  folded back into the LFSR so nothing is optimised away. HyperRAM clock forwarding is HI = 1, LO = 0,
  as in a HyperBus controller; the PLL phase-shift controls are tied off.
- ti60f225_pinplan.sdc: the Interface Designer constraints plus a clock-group split between the
  calibrated read clock and ram_clk/ram_clk90 (the real controller handles that crossing).
- ti60f225_pinplan.xml: Efinity project, Ti60F225 C4, configuration SPI active x4.

The core logic is meaningless; the point is that synthesis, placement, routing and bitstream generation
accept the periphery (pins, I/O standards, DDIO registers, PLL) with configuration in x4 mode.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.join(HERE, "build")
NAME = "ti60f225_pinplan"


def ports():
    t = open(os.path.join(BUILD, "outflow", NAME + "_template.v")).read()
    out = []
    for m in re.finditer(r"\)\s*(input|output)\s*(?:\[(\d+):(\d+)\])?\s*(\w+)", t):
        d, msb, lsb, name = m.groups()
        # keep [0:0] buses as buses: the periphery names them name[0]
        out.append((d, int(msb) - int(lsb) + 1 if msb else 0, name))
    return out


def main():
    ps = ports()
    clocks = {"ram_clk", "ram_clk90", "ram_clk_cal", "clk100m"}
    lines = [f"// Generated by efinity/pinplan/stub.py: placeholder core for the pin-plan compile.",
             f"module {NAME} ("]
    decl = []
    for d, w, n in ps:
        decl.append(f"    {d} {'[%d:0] ' % (w - 1) if w else ''}{n}")
    lines.append(",\n".join(decl))
    lines.append(");")
    lines.append("    reg [31:0] lfsr = 32'h1;")
    lines.append("    reg [31:0] cal_q = 32'h0;")
    ins = [(w, n) for d, w, n in ps if d == "input" and n not in clocks]
    cal_ins = [(w, n) for w, n in ins if n.startswith(("hbc_dq_IN", "hbc_rwds_IN"))]
    other_ins = [(w, n) for w, n in ins if (w, n) not in cal_ins]
    cal_bits = " ^ ".join(f"(^{n})" for w, n in cal_ins) or "1'b0"
    lines.append("    always @(posedge ram_clk_cal) cal_q <= {cal_q[30:0], %s};" % cal_bits)
    other_bits = " ^ ".join(f"(^{n})" for w, n in other_ins) or "1'b0"
    lines.append("    always @(posedge ram_clk)\n"
                 "        lfsr <= {lfsr[30:0], lfsr[31] ^ lfsr[21] ^ lfsr[1] ^ lfsr[0] ^ cal_q[31] ^ %s};" % other_bits)
    k = 0
    for d, w, n in ps:
        if d != "output":
            continue
        if n == "hbc_ck_p_HI":
            lines.append(f"    assign {n} = 1'b1;")
        elif n == "hbc_ck_p_LO":
            lines.append(f"    assign {n} = 1'b0;")
        elif n.startswith("hbc_cal_"):
            lines.append(f"    assign {n} = {max(w, 1)}'d0;")
        else:
            bits = ", ".join(f"lfsr[{(k + i) % 32}]" for i in range(max(w, 1)))
            lines.append(f"    assign {n} = {{{bits}}};")
            k += max(w, 1)
    lines.append("endmodule")
    open(os.path.join(BUILD, NAME + "_stub.v"), "w").write("\n".join(lines) + "\n")

    sdc = open(os.path.join(BUILD, "outflow", NAME + ".pt.sdc")).read()
    sdc += "\n# stub: the calibrated read clock is a separate domain\n"
    sdc += "set_clock_groups -asynchronous -group {ram_clk_cal} -group {ram_clk ram_clk90}\n"
    open(os.path.join(BUILD, NAME + ".sdc"), "w").write(sdc)

    # project file: Efinity's own Ti60F225 tutorial project, with our names, files and x4 configuration
    tut = os.path.join(os.environ.get("EFINITY_HOME", os.path.expanduser("~/efinity/2026.1")),
                       "project", "Ti60F225_devkit_tutorial", "Ti60F225_devkit_tutorial.xml")
    xml = open(tut).read()
    xml = re.sub(r'<efx:project name="[^"]*"', f'<efx:project name="{NAME}"', xml)
    xml = re.sub(r'<efx:top_module name="[^"]*"/>', f'<efx:top_module name="{NAME}"/>', xml)
    xml = re.sub(r'(\s*<efx:design_file [^>]*/>)+',
                 f'\n        <efx:design_file name="{NAME}_stub.v" version="default" library="default"/>', xml, count=1)
    xml = re.sub(r'<efx:sdc_file name="[^"]*"/>', f'<efx:sdc_file name="{NAME}.sdc"/>', xml)
    xml = re.sub(r'<efx:ip_info>.*?</efx:ip_info>', '<efx:ip_info/>', xml, flags=re.S)
    xml = re.sub(r'\s*<efx:param name="include" [^>]*/>', '', xml)
    xml = re.sub(r'(<efx:bitstream_generation.*?<efx:param name="width" value=")\d(")', r'\g<1>4\2', xml, flags=re.S)
    assert 'name="width" value="4"' in xml and f'{NAME}_stub.v' in xml
    open(os.path.join(BUILD, NAME + ".xml"), "w").write(xml)
    print("wrote stub, sdc and project into", BUILD)


if __name__ == "__main__":
    main()
